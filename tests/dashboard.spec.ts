import { test, expect } from '@playwright/test';
test.beforeEach(async({page})=>{
  await page.addInitScript(()=>{
    const w=window as any;
    w.opened=[];
    w.chrome={storage:{local:{get:async(key:string)=>({[key]:JSON.parse(localStorage.getItem(key)??'null')}),set:async(value:any)=>{if(w.failSave)throw new Error('Simulated storage failure');for(const key in value)localStorage.setItem(key,JSON.stringify(value[key]));}}},tabs:{create:async({url}:{url:string})=>{if(w.failUrl===url)throw new Error('Simulated tab failure');w.opened.push(url);return{id:w.opened.length};}}};
  });
  await page.goto('/');
  await expect(page.locator('.portal')).toHaveCount(34);
});
test('portal opening, failure retry, status reset and persistence',async({page})=>{
  const first=page.locator('.portal').first();
  await first.getByLabel('Check status').selectOption('Ready');
  await expect(first.getByLabel('Check status')).toHaveValue('Ready');
  await page.reload();
  await expect(first.getByLabel('Check status')).toHaveValue('Ready');
  await first.getByLabel('Enabled').click();
  await expect(first.getByLabel('Enabled')).not.toBeChecked();
  await page.getByRole('button',{name:'Open all enabled'}).click();
  await expect(page.getByRole('status')).toContainText('Opened 31 of 31');
  expect(await page.evaluate(()=>(window as any).opened.length)).toBe(31);
  await first.getByLabel('Select ImmoScout24').check();
  await page.getByRole('button',{name:'Open selected (1)'}).click();
  await expect(first.getByLabel('Check status')).toHaveValue('Not checked');
  await page.evaluate(()=>{(window as any).failUrl=JSON.parse(localStorage.getItem('houseHunt')!).portals[0].url;});
  await first.getByRole('button',{name:'Open portal'}).click();
  await expect(page.getByRole('button',{name:'Retry failed'})).toBeVisible();
  await page.evaluate(()=>{(window as any).failUrl=null;});
  await page.getByRole('button',{name:'Retry failed'}).click();
  await expect(page.getByRole('status')).toContainText('Opened 1 of 1');
});
test('manual matching, duplicate edit, criteria updates and form recovery',async({page})=>{
  await page.getByRole('button',{name:'Apartments',exact:true}).click();
  await page.getByRole('button',{name:'+ Add apartment',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Title',{exact:true}).fill('Winterhude flat');
  await dialog.getByLabel('Listing URL').fill('https://example.com/flat');
  await dialog.getByLabel('City',{exact:true}).fill('Hamburg');
  await dialog.getByLabel('Rooms',{exact:true}).fill('2.5');
  await dialog.getByLabel('Area (m²)').fill('70');
  await dialog.getByLabel('Monthly rent (€)').fill('1400');
  await dialog.getByLabel('Heating in this rent').selectOption('Included');
  await dialog.getByLabel('Available / agreed start date').fill('2027-05-31');
  await page.evaluate(()=>{(window as any).failSave=true;});
  await dialog.getByRole('button',{name:'Save apartment'}).click();
  await expect(dialog.getByRole('alert')).toContainText('Simulated storage failure');
  await expect(dialog.getByLabel('Title',{exact:true})).toHaveValue('Winterhude flat');
  await page.evaluate(()=>{(window as any).failSave=false;});
  await dialog.getByRole('button',{name:'Save apartment'}).click();
  await expect(page.locator('.badge')).toHaveText('Matches');
  await page.getByRole('button',{name:'+ Add apartment',exact:true}).click();
  await dialog.getByLabel('Listing URL').fill('https://example.com/flat');
  page.once('dialog',d=>d.accept());
  await dialog.getByRole('button',{name:'Save apartment'}).click();
  await expect(dialog.getByLabel('Title',{exact:true})).toHaveValue('Winterhude flat');
  await page.keyboard.press('Escape');
  await expect(dialog).toHaveCount(0);
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Maximum rent incl. heating (€)').fill('1300');
  await page.getByRole('button',{name:'Save criteria'}).click();
  await page.getByRole('button',{name:'Apartments',exact:true}).click();
  await expect(page.locator('.apartment')).toHaveCount(0);
  await page.getByLabel('Include archived').check();
  await expect(page.locator('.badge')).toHaveText('Does not match');
  await expect(page.locator('.apartment').getByLabel('Progress for Winterhude flat')).toHaveValue('Archived');
  await expect(page.locator('.apartment')).toHaveCount(1);
});
test('backup restore validates, confirms and persists an empty portal list',async({page})=>{
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  const input=page.getByLabel('Restore a backup (replaces current data)');
  await input.setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('{"version":2}')});
  await expect(page.getByRole('alert')).toContainText('Invalid backup');
  const data=await page.evaluate(()=>JSON.parse(localStorage.getItem('houseHunt')!));
  data.portals=[];
  page.once('dialog',d=>d.accept());
  await input.setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(data))});
  await expect(page.getByRole('status')).toHaveText('Backup restored.');
  await page.reload();
  await expect(page.getByRole('button',{name:'Settings',exact:true})).toHaveAttribute('aria-current','page');
  await page.getByRole('button',{name:'Portals',exact:true}).click();
  await expect(page.locator('.portal')).toHaveCount(0);
  await expect(page.getByText('Add a portal to start your housing checklist.')).toBeVisible();
});
test('apartment card opens a new tab while controls, removal and section refresh work',async({page,context})=>{
  await page.getByRole('button',{name:'Apartments',exact:true}).click();
  await page.getByRole('button',{name:'+ Add apartment',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Title',{exact:true}).fill('A home to keep');
  await dialog.getByLabel('Listing URL').fill('https://example.com/saved-home');
  await dialog.getByLabel('Notes').fill('Keep this note');
  await dialog.getByRole('button',{name:'Save apartment'}).click();
  await expect(dialog).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button',{name:'Apartments',exact:true})).toHaveAttribute('aria-current','page');
  const card=page.locator('.apartment');
  await card.getByLabel('Progress for A home to keep').selectOption('Viewing');
  await expect(card.getByLabel('Progress for A home to keep')).toHaveValue('Viewing');
  expect(context.pages()).toHaveLength(1);
  await card.getByRole('button',{name:'Edit details'}).click();
  await expect(dialog.getByLabel('Notes')).toHaveValue('Keep this note');
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  expect(context.pages()).toHaveLength(1);
  await context.route('https://example.com/saved-home',r=>r.fulfill({body:'Listing'}));
  const popupPromise=context.waitForEvent('page');
  await card.click({position:{x:25,y:25}});
  const popup=await popupPromise;await popup.waitForLoadState();
  expect(popup.url()).toBe('https://example.com/saved-home');
  await popup.close();
  await expect(card).toHaveClass(/is-visited/);
  await page.reload();
  await expect(card).toHaveClass(/is-visited/);
  await expect(card.getByLabel('Progress for A home to keep')).toHaveValue('Viewing');
  await card.getByRole('button',{name:'Remove property'}).click();
  await expect(card).toHaveCount(0);
  expect(context.pages()).toHaveLength(1);
  await page.getByRole('button',{name:'Undo remove'}).click();
  await expect(card.getByLabel('Progress for A home to keep')).toHaveValue('Viewing');
  await expect(card.getByText('Keep this note')).toBeVisible();
  await card.getByRole('button',{name:'Remove property'}).click();
  await expect(card).toHaveCount(0);
  await page.reload();
  await expect(card).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Apartments',exact:true})).toHaveAttribute('aria-current','page');
});
test('stale dashboard saves cannot overwrite newer records',async({page})=>{
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Maximum rent incl. heating (€)').fill('1200');
  await page.evaluate(()=>{const d=JSON.parse(localStorage.getItem('houseHunt')!);d.criteria.rent=1350;localStorage.setItem('houseHunt',JSON.stringify(d));});
  await page.getByRole('button',{name:'Save criteria'}).click();
  await expect(page.getByRole('alert')).toContainText('Data changed in another dashboard');
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('houseHunt')!).criteria.rent)).toBe(1350);
  await expect(page.getByLabel('Maximum rent incl. heating (€)')).toHaveValue('1200');
});

